test('a shared piece opens directly, survives reload, and follows browser history', async ({ page, context }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/?piece=nursery-aikendrum');
  await expect(page.getByRole('heading', { name: 'Aiken Drum', exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: /Original score, measures/ }).locator('svg')).toBeVisible();
  await expect(page.getByRole('button', { name: '▶ Play', exact: true })).toBeVisible();
  await page.evaluate(() => navigator.serviceWorker.ready);
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Aiken Drum', exact: true })).toBeVisible();
  await context.setOffline(false);
  await page.getByRole('link', { name: 'Library', exact: true }).click();
  await page.getByLabel('Find a song', { exact: true }).pressSequentially('London Bridge');
  await page.getByRole('button', { name: 'Open London Bridge', exact: true }).click();
  await expect(page).toHaveURL(/\?piece=nursery-londonbridge$/);
  await page.goBack(); await expect(page.getByLabel('Find a song', { exact: true })).toBeVisible();
  await page.goBack(); await expect(page.getByRole('heading', { name: 'Aiken Drum', exact: true })).toBeVisible();
  await page.goForward(); await page.goForward();
  await expect(page.getByRole('heading', { name: 'London Bridge', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('share copies a public URL, offers a manual fallback, and never shares a replacement import', async ({ page, context }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'share', { configurable: true, value: undefined });
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (url: string) => { (window as any).copiedLink = url; } } });
  });
  await page.goto('/?piece=nursery-aikendrum');
  await page.getByRole('button', { name: 'Share Aiken Drum', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Link copied.' })).toBeVisible();
  const url = await page.getByLabel('Link to Aiken Drum', { exact: true }).inputValue();
  expect(await page.evaluate(() => (window as any).copiedLink)).toBe(url);
  const recipient = await context.newPage(); await recipient.goto(url);
  await expect(recipient.getByRole('heading', { name: 'Aiken Drum', exact: true })).toBeVisible();
  await recipient.close();
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => { throw new Error('Denied'); } } }); });
  await page.getByRole('button', { name: 'Share Aiken Drum', exact: true }).click();
  await expect(page.getByText('Select and copy the link below.')).toBeVisible();
  await page.getByLabel('Link to Aiken Drum', { exact: true }).focus();
  expect(await page.getByLabel('Link to Aiken Drum', { exact: true }).evaluate((el: HTMLInputElement) => el.selectionEnd! - el.selectionStart!)).toBe(url.length);
  await page.evaluate(() => { Object.defineProperty(navigator, 'share', { value: async (data: ShareData) => { (window as any).nativeShared = data; } }); });
  await page.getByRole('button', { name: 'Share Aiken Drum', exact: true }).click();
  await expect(page.getByText('Link shared.', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as any).nativeShared.url)).toBe(url);
  const midi = new Midi(); midi.name = 'My private arrangement'; midi.addTrack().addNote({ midi: 60, time: 0, duration: 2 });
  await page.getByLabel('Choose MIDI file').setInputFiles({ name: 'nursery-aikendrum.mid', mimeType: 'audio/midi', buffer: Buffer.from(midi.toArray()) });
  await expect(page.getByRole('heading', { name: 'My private arrangement', exact: true })).toBeVisible();
  await expect(page).not.toHaveURL(/piece=/);
  await expect(page.getByRole('button', { name: /^Share / })).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'Saved on this device' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'My private arrangement', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Share / })).toHaveCount(0);
});

test('invalid and failed links show errors; leaving an in-flight link cancels it', async ({ page }) => {
  await page.goto('/?piece=missing');
  await expect(page.getByRole('alert')).toContainText('not in the free collection');
  await expect(page.getByRole('region', { name: 'Music player' })).toHaveCount(0);
  await page.route('**/music/nursery-aikendrum/score.mid', route => route.fulfill({ status: 503, body: 'unavailable' }));
  await page.goto('/?piece=nursery-aikendrum');
  await expect(page.getByRole('alert')).toContainText('could not be downloaded');
  await page.unroute('**/music/nursery-aikendrum/score.mid');
  await page.getByRole('button', { name: 'Retry linked piece', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Aiken Drum', exact: true })).toBeVisible();
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/music/nursery-londonbridge/score.mid', async route => { await pending; await route.continue().catch(() => {}); });
  await page.goto('/?piece=nursery-londonbridge', { waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('status').filter({ hasText: 'Opening linked piece' })).toBeVisible();
  await page.getByRole('link', { name: 'Library', exact: true }).click();
  release();
  await page.getByRole('button', { name: /Browse Mozart/ }).click();
  await expect(page.getByLabel('Composer', { exact: true })).toHaveValue('W. A. Mozart');
  await expect(page).toHaveURL(/\/library$/);
});

test('dark shelves and favourites are distinct, and a Mozart search can escape favourites', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' }); await page.goto('/library');
  const free = page.getByRole('button', { name: 'Free collection', exact: true });
  await expect(free).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('Find a song', { exact: true }).pressSequentially('Aiken Drum');
  await page.getByRole('button', { name: 'Favourite Aiken Drum', exact: true }).click();
  const star = page.getByRole('button', { name: 'Favourite Aiken Drum', exact: true });
  await expect(star).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('Find a song', { exact: true }).fill('');
  const favourites = page.getByRole('button', { name: 'Favourites (1)', exact: true });
  await favourites.click();
  await page.getByLabel('Composer', { exact: true }).selectOption('W. A. Mozart');
  await expect(page.getByText('No favourites match these filters.')).toBeVisible();
  await expect(page.getByText('0 pieces found · In your favourites')).toBeVisible();
  await expect(favourites).toHaveAttribute('aria-pressed', 'true');
  await expect(free).toHaveAttribute('aria-pressed', 'false');
  const active = await favourites.evaluate(el => ({ bg: getComputedStyle(el).backgroundColor, fg: getComputedStyle(el).color }));
  const inactive = await free.evaluate(el => ({ bg: getComputedStyle(el).backgroundColor, fg: getComputedStyle(el).color }));
  expect(active.bg).not.toBe(inactive.bg); expect(active.fg).not.toBe(inactive.fg);
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({ path: 'test-results/dark-favourites-empty.png', fullPage: true });
  await page.getByRole('button', { name: 'Search all free pieces', exact: true }).click();
  await expect(free).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByLabel('Composer', { exact: true })).toHaveValue('W. A. Mozart');
  await expect(page.locator('article')).not.toHaveCount(0);
  await page.getByLabel('Find a song', { exact: true }).pressSequentially('Turkish');
  await expect(page.getByRole('heading', { name: /Turkish March/ })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: /Turkish March/ })).toBeVisible();
  await page.getByRole('button', { name: /Browse Chopin/ }).click();
  await expect(page.getByLabel('Find a song', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Composer', { exact: true })).toHaveValue('F. F. Chopin');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.evaluate(() => scrollTo(0,0));
  await page.screenshot({ path: 'test-results/dark-composers-mobile.png' });
});

test('Vivaldi discovery, source score, saved filters, sharing and playback work together', async ({ page }) => {
  const title = 'Violin Concerto in A minor, Op. 3 No. 6 — I. Allegro';
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/library');
  await page.getByRole('button', { name: 'Browse Vivaldi, Antonio', exact: true }).click();
  await expect(page.getByLabel('Composer', { exact: true })).toHaveValue('A. Vivaldi');
  await expect(page.getByText(/196 pieces found · Free collection/)).toBeVisible();
  await page.getByLabel('Find a song', { exact: true }).pressSequentially('A minor');
  await expect(page.getByText(/3 pieces found · Free collection/)).toBeVisible();
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await expect(card.getByRole('img', { name: 'Portrait of Antonio Vivaldi' })).toBeVisible();
  await card.getByRole('button', { name: `Favourite ${title}`, exact: true }).click();
  await card.getByRole('button', { name: 'Save to my files', exact: true }).click();
  await expect(card.getByRole('button', { name: 'Saved to my files', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Find a song', { exact: true })).toHaveValue('A minor');
  await expect(card.getByRole('button', { name: `Favourite ${title}`, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await card.getByText('About, downloads & credits', { exact: true }).click();
  await expect(card.getByText(/original PDF contains the complete concerto/)).toBeVisible();
  const pdfUrl = await card.getByRole('link', { name: 'Download PDF', exact: true }).getAttribute('href');
  const response = await page.request.get(pdfUrl!); expect(response.ok()).toBe(true);
  expect((await response.body()).subarray(0,5).toString()).toBe('%PDF-');
  await card.getByRole('button', { name: `Open ${title}`, exact: true }).click();
  await expect(page).toHaveURL(/\?piece=mutopia-2048-6-1$/);
  await expect(page.getByRole('img', { name: /Staff notation/ }).locator('svg')).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: '▶ Play', exact: true }).click();
  await expect.poll(async () => Number(await page.getByRole('slider', { name: 'Playback position', exact: true }).inputValue())).toBeGreaterThan(.2);
  await page.getByRole('link', { name: 'Profile', exact: true }).click();
  await page.getByRole('link', { name: 'Player', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: '▶ Play', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'PDF score', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Open PDF score in a new tab ↗' })).toBeVisible();
  const icon = await page.request.get('/favicon.ico'); expect(icon.ok()).toBe(true);
  expect(errors).toEqual([]);
});
